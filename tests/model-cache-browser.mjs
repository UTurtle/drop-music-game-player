import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5193';
const body = Buffer.from('cache lifecycle fixture, not an inference model');
const name = 'fixture.onnx', path = '/models/mapper-mini-v1/';
const manifest = { id: 'mapper-mini-v1', files: [{ name, bytes: body.length, sha256: createHash('sha256').update(body).digest('hex') }] };
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH, headless: true });
try {
 const context = await browser.newContext();
 await context.addInitScript(() => {
  Object.defineProperty(navigator, 'gpu', { configurable: true, value: { requestAdapter: async () => ({ isFallbackAdapter: false, features: new Set(['shader-f16']) }) } });
  localStorage.setItem('drop-language', 'en');
 });
 const page = await context.newPage(), errors = [], uploads = [];
 page.on('pageerror', e => errors.push(e.message));
 page.on('request', r => { if (r.method() !== 'GET') uploads.push(r.url()); });
 let downloads = 0, corrupt = false, slow = false;
 await page.route('**/models/mapper-mini-v1/manifest.json', r => r.fulfill({ json: manifest }));
 await page.route('**/models/mapper-mini-v1/fixture.onnx', async r => { downloads++; if (slow) await new Promise(resolve => setTimeout(resolve, 1000)); await r.fulfill({ body: corrupt ? Buffer.alloc(body.length) : body }).catch(() => {}); });
 await page.goto(base + '/create');
 await page.getByRole('button', { name: 'Download model', exact: true }).waitFor();
 assert.equal(downloads, 0, 'Opening the page must not download weights');
 await page.evaluate(async () => { await (await caches.open('other-app')).put('/unrelated', new Response('keep')); });
 await page.evaluate(async () => { await (await caches.open('drop-model-obsolete')).put('/old-model', new Response('old')); });
 await page.getByRole('button', { name: 'Download model', exact: true }).click();
 await page.getByText('Saved ·').waitFor();
 assert.equal(await page.evaluate(() => caches.has('drop-model-obsolete')), false);
 assert.equal(downloads, 1);
 await page.reload(); await page.getByText('Saved ·').waitFor();
 assert.equal(downloads, 1, 'Reload must reuse the model cache');
 await page.locator('#creator-title').fill('Keep this title');
 await page.getByRole('button', { name: 'Delete saved model', exact: true }).click();
 await page.getByText('Saved model removed.', { exact: false }).waitFor();
 assert.equal(await page.locator('#creator-title').inputValue(), 'Keep this title');
 assert.deepEqual(await page.evaluate(() => caches.keys()), ['other-app']);
 assert.equal(await page.evaluate(() => localStorage.getItem('drop-language')), 'en');
 await page.reload(); await page.getByRole('button', { name: 'Download model', exact: true }).waitFor(); assert.equal(downloads, 1);
 corrupt = true;
 await page.getByRole('button', { name: 'Download model', exact: true }).click();
 await page.getByText('Could not save the model.', { exact: false }).waitFor();
 assert.deepEqual(await page.evaluate(() => caches.keys()), ['other-app']);
 corrupt = false; slow = true;
 await page.getByRole('button', { name: 'Download model', exact: true }).click();
 await page.getByRole('button', { name: 'Cancel download', exact: true }).click();
 await page.getByText('Download canceled.', { exact: false }).waitFor();
 assert.deepEqual(await page.evaluate(() => caches.keys()), ['other-app']);
 assert.deepEqual(errors, []); assert.deepEqual(uploads, []);
 await mkdir('output/model-cache', { recursive: true });
 await page.screenshot({ path: 'output/model-cache/controls.png', fullPage: true });
 await writeFile('output/model-cache/report.json', JSON.stringify({ passed: true, downloads, uploads, errors, cases: ['opt-in', 'reuse', 'delete preserves other data', 'no re-download after delete', 'checksum failure cleanup', 'cancel cleanup'] }, null, 2));
 console.log('Model cache lifecycle PASS');
} finally { await browser.close(); }
